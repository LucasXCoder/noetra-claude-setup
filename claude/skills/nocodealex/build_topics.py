"""Regenerate the atom index block inside each references/topics/*.md file.

The atom/edge store is the source of truth; topic files are a readable projection of it.
Everything between the AUTO markers is rewritten from atoms.jsonl on every run; hand-written
prose ABOVE the opening marker is preserved.
"""
import collections
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
TOPICS = HERE / "references" / "topics"
BEGIN = "<!-- AUTO:atoms BEGIN -- regenerated by build_topics.py, do not edit below -->"
END = "<!-- AUTO:atoms END -->"
TITLES = {
    "usage-limits": "Usage limits, tokens, context and model routing",
    "claude-code-mastery": "Claude Code commands, settings, effort levels, hooks and fixes",
    "skills-mcp-ecosystem": "Skills, plugins, MCP servers and open-source tools",
    "agent-teams": "Multi-Claude panels, judges, routines and agent teams",
    "prompting-quality": "Prompting patterns and output quality",
    "build-sell-career": "Building, launching, selling, content and career",
    "creator-news": "Who Alex Chen is, what he ships, and his AI-news takes",
}


def main() -> None:
    TOPICS.mkdir(parents=True, exist_ok=True)
    atoms = [json.loads(l) for l in (HERE / "atoms.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    edges = [json.loads(l) for l in (HERE / "edges.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    manifest = json.loads((HERE / "sources" / "manifest.json").read_text(encoding="utf-8"))
    url = {it["id"]: it["url"] for it in manifest["items"]}

    out_edges = collections.defaultdict(list)
    for e in edges:
        out_edges[e["from"]].append(e)
    by_topic = collections.defaultdict(list)
    for a in atoms:
        by_topic[a["topic"]].append(a)

    for topic, items in sorted(by_topic.items()):
        lines = [BEGIN, "", f"*{len(items)} atoms.*", ""]
        for typ in sorted({a["type"] for a in items}):
            lines += [f"### {typ}", ""]
            for a in sorted((x for x in items if x["type"] == typ), key=lambda x: x["id"]):
                src = " ".join(f"[{s}]({url.get(s, '')})" for s in a["sources"])
                lines.append(f"- `{a['id']}` *{a['confidence']}* — {a['text']}")
                if a.get("verbatim"):
                    lines.append(f"  > “{a['verbatim']}”")
                lines.append(f"  — {src}")
                for e in out_edges.get(a["id"], []):
                    note = f" — {e['note']}" if e.get("note") else ""
                    lines.append(f"  ↳ *{e['rel']}* `{e['to']}`{note}")
                lines.append("")
        lines.append(END)
        path = TOPICS / f"{topic}.md"
        prose = HERE / "references" / "prose" / f"{topic}.md"
        head = f"# {TITLES.get(topic, topic)}\n\nEvery atom in this topic, with its source and outgoing reasoning edges.\n\n"
        if prose.exists():  # hand-written overview lives in its own file so regeneration can never eat it
            head = prose.read_text(encoding="utf-8").rstrip() + "\n\n---\n\n## Atom index\n\n"
        elif path.exists() and BEGIN in (cur := path.read_text(encoding="utf-8")):
            head = cur.split(BEGIN)[0]
        path.write_text(head + "\n".join(lines) + "\n", encoding="utf-8")
        print(f"{topic}.md  {len(items)} atoms")


if __name__ == "__main__":
    main()
